/**
 * Build all four faces of dsh-notes:
 *
 *   server/lib/server.js  self-contained Node server bundle
 *   lib/index.js          DSH host plugin (ESM)
 *   lib/client.js         DSH browser plugin (CJS wrapped in __ModuleLoader__)
 *   web/assets/app.js     standalone browser SPA (React bundled)
 *
 * React is external only in the DSH browser bundle, because DSH seeds it as a
 * platform module. Every other third-party package is inlined so an installed
 * plugin or a copied server has no runtime dependency tree.
 *
 * The esbuild CLI is invoked through a child process with inherited stdio. That
 * works in confined environments that refuse piped child stdio, and keeps the
 * build script dependency-free beyond the installed esbuild package.
 */

import { spawnSync } from 'node:child_process'
import { cp, mkdir, readFile, rm, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const root = join(here, '..')
const version = JSON.parse(await readFile(join(root, 'package.json'), 'utf8')).version
const esbuildBin = join(root, 'node_modules', 'esbuild', 'bin', 'esbuild')

const defineVersion = `--define:__DSH_NOTES_VERSION__=${JSON.stringify(version)}`
const defineNodeEnv = '--define:process.env.NODE_ENV="production"'

function runEsbuild(args) {
  const result = spawnSync(process.execPath, [esbuildBin, ...args], {
    cwd: root,
    stdio: 'inherit',
    windowsHide: true,
  })
  if (result.error !== undefined) throw result.error
  if (result.status !== 0) throw new Error(`esbuild exited with status ${result.status}`)
}

async function buildServer() {
  await mkdir(join(root, 'server', 'lib'), { recursive: true })
  runEsbuild([
    join(root, 'src', 'server', 'cli.ts'),
    '--bundle',
    '--platform=node',
    '--target=node24',
    '--format=esm',
    '--outfile=' + join(root, 'server', 'lib', 'server.js'),
    '--log-level=warning',
    defineVersion,
    defineNodeEnv,
  ])
}

async function buildHost() {
  runEsbuild([
    join(root, 'src', 'host', 'index.ts'),
    '--bundle',
    '--platform=node',
    '--target=node24',
    '--format=esm',
    '--outfile=' + join(root, 'lib', 'index.js'),
    '--log-level=warning',
    defineVersion,
    defineNodeEnv,
  ])
}

async function buildClient() {
  const raw = join(root, 'lib', 'client.raw.js')
  runEsbuild([
    join(root, 'src', 'client', 'index.tsx'),
    '--bundle',
    '--platform=browser',
    '--target=es2020',
    '--format=cjs',
    '--jsx=automatic',
    '--external:react',
    '--external:react/jsx-runtime',
    '--outfile=' + raw,
    '--log-level=warning',
    defineVersion,
    defineNodeEnv,
  ])
  const code = await readFile(raw, 'utf8')
  const wrapped = `/**
 * dsh-notes browser half (generated by scripts/build.mjs).
 *
 * The DSH module loader materializes this bundle lazily. React stays external
 * and is resolved through the loader's platform-module table.
 */
window.__ModuleLoader__.load({
  id: "dsh-notes",
  factory: (require) => {
    var module = { exports: {} };
    var exports = module.exports;
${code}
    return module.exports;
  },
});
`
  await writeFile(join(root, 'lib', 'client.js'), wrapped, 'utf8')
  await rm(raw, { force: true })
}

async function buildWeb() {
  const assets = join(root, 'web', 'assets')
  await mkdir(assets, { recursive: true })
  runEsbuild([
    join(root, 'src', 'web', 'main.tsx'),
    '--bundle',
    '--platform=browser',
    '--target=es2020',
    '--format=iife',
    '--jsx=automatic',
    '--outfile=' + join(assets, 'app.js'),
    '--log-level=warning',
    defineNodeEnv,
  ])
  await cp(join(root, 'media', 'icon.svg'), join(assets, 'icon.svg'))
  await writeFile(join(root, 'web', 'index.html'), indexHtml(version), 'utf8')
  await writeFile(join(root, 'web', 'manifest.webmanifest'), JSON.stringify({
    name: 'DSH Notes',
    short_name: 'Notes',
    description: 'Markdown notes served by dsh-notes-server.',
    start_url: '.',
    scope: '.',
    display: 'standalone',
    background_color: '#f7f7f8',
    theme_color: '#2f6feb',
    icons: [
      { src: 'assets/icon.svg', sizes: 'any', type: 'image/svg+xml', purpose: 'any' },
    ],
  }, null, 2) + '\n', 'utf8')
}

function escapeHtml(value) {
  return String(value).replace(/[&<>"']/g, (ch) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[ch]))
}

function indexHtml(version) {
  return `<!doctype html>
<html lang="zh-CN">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
  <base href="__BASE_HREF__">
  <meta name="color-scheme" content="light dark">
  <meta name="theme-color" content="#2f6feb">
  <meta name="dsh-notes-version" content="${escapeHtml(version)}">
  <title>DSH Notes</title>
  <link rel="icon" href="assets/icon.svg" type="image/svg+xml">
  <link rel="manifest" href="manifest.webmanifest">
  <script defer src="assets/app.js"></script>
</head>
<body>
  <div id="dsh-notes-root"></div>
</body>
</html>
`
}

await rm(join(root, 'server', 'lib'), { recursive: true, force: true })
await rm(join(root, 'lib'), { recursive: true, force: true })
await mkdir(join(root, 'lib'), { recursive: true })
await rm(join(root, 'web', 'assets'), { recursive: true, force: true })

console.log('building server…')
await buildServer()
console.log('building host…')
await buildHost()
console.log('building DSH client…')
await buildClient()
console.log('building web app…')
await buildWeb()

const sizes = await Promise.all([
  ['server/lib/server.js', join(root, 'server', 'lib', 'server.js')],
  ['lib/index.js', join(root, 'lib', 'index.js')],
  ['lib/client.js', join(root, 'lib', 'client.js')],
  ['web/assets/app.js', join(root, 'web', 'assets', 'app.js')],
].map(async ([label, file]) => [label, (await readFile(file)).byteLength]))
for (const [label, bytes] of sizes) console.log(`${label.padEnd(24)} ${(bytes / 1024).toFixed(1)} KiB`)
