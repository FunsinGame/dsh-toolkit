/**
 * Build both halves of dsh-design-mind, plus a small ESM bundle of the pure
 * modules the unit tests import.
 *
 * Host: an ESM entry that registers the routes.
 * Client: one CJS bundle wrapped in `window.__ModuleLoader__.load`. React and
 * its JSX runtime stay external because DSH seeds them as platform modules.
 */

import { build } from 'esbuild'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const root = join(here, '..')
const lib = join(root, 'lib')
await mkdir(lib, { recursive: true })

const version = JSON.parse(await readFile(join(root, 'package.json'), 'utf8')).version

console.log('building host…')
await build({
  entryPoints: [join(root, 'src', 'host', 'index.ts')],
  bundle: true,
  platform: 'node',
  target: 'node20',
  format: 'esm',
  outfile: join(lib, 'index.js'),
  minify: false,
  sourcemap: false,
  logLevel: 'info',
  define: {
    __DESIGN_MIND_VERSION__: JSON.stringify(version),
  },
})

console.log('building client…')
const result = await build({
  entryPoints: [join(root, 'src', 'client', 'index.tsx')],
  bundle: true,
  platform: 'browser',
  target: 'es2020',
  format: 'cjs',
  write: false,
  minify: false,
  sourcemap: false,
  logLevel: 'info',
  jsx: 'automatic',
  external: ['react', 'react/jsx-runtime', 'react-dom', 'react-dom/client'],
  define: {
    'process.env.NODE_ENV': '"production"',
    __DESIGN_MIND_VERSION__: JSON.stringify(version),
  },
})

const code = result.outputFiles[0].text
const wrapped = `/**
 * dsh-design-mind browser half (generated by scripts/build.mjs).
 *
 * The DSH module loader materializes this bundle lazily. React stays external
 * and is resolved through the loader's platform-module table.
 */
window.__ModuleLoader__.load({
  id: "dsh-design-mind",
  factory: (require) => {
    var module = { exports: {} };
    var exports = module.exports;
${code}
    return module.exports;
  },
});
`
await writeFile(join(lib, 'client.js'), wrapped, 'utf8')

console.log('building testable…')
await build({
  entryPoints: [join(root, 'src', 'testable.ts')],
  bundle: true,
  platform: 'node',
  target: 'node20',
  format: 'esm',
  outfile: join(lib, 'testable.js'),
  minify: false,
  sourcemap: false,
  logLevel: 'info',
})

const hostSize = (await readFile(join(lib, 'index.js'))).byteLength
const clientSize = (await readFile(join(lib, 'client.js'))).byteLength
console.log(`host:   ${(hostSize / 1024).toFixed(1)} KiB`)
console.log(`client: ${(clientSize / 1024).toFixed(1)} KiB`)
